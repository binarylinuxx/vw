namespace vw {

struct ClickEvent {
  double x = 0.0;
  double y = 0.0;
  std::uint32_t button = 0;
};

struct DragEvent {
  double x = 0.0;
  double y = 0.0;
  double start_x = 0.0;
  double start_y = 0.0;
  double dx = 0.0;
  double dy = 0.0;
  double delta_x = 0.0;
  double delta_y = 0.0;
  std::uint32_t button = 0;
  bool cancelled = false;
};

struct FocusEvent {
  bool active = false;
  // zwwm focus-grab dismissal reason; meaningful only when !active.
  std::uint32_t code = 0;

  std::string_view reason() const {
    constexpr std::array<std::string_view, 5> names{
        "outside", "unmapped", "replaced", "locked", "released"};
    return code < names.size() ? names[code] : "unknown";
  }
};

struct ScrollEvent {
  double x = 0.0;
  double y = 0.0;
  // Vertical distance in surface pixels; positive scrolls down.
  double delta = 0.0;
};

// One finger on a widget with on_touch. Each finger has its own id and is
// delivered to the widget it went down on until it lifts.
struct TouchEvent {
  enum class Phase : std::uint8_t { down, motion, up, cancel };
  Phase phase = Phase::down;
  std::int32_t id = 0;
  double x = 0.0;
  double y = 0.0;
  double start_x = 0.0;
  double start_y = 0.0;
  // Fingers on this surface's on_touch widgets right now, this one included
  // (an up still counts the finger lifting).
  std::size_t fingers = 0;
};

struct KeyEvent {
  std::uint32_t keysym = 0;
  // xkb keysym name: "Escape", "Return", "Down", "a", "F5", ...
  std::string name;
  // UTF-8 text the key produces, if any.
  std::string text;
  bool ctrl = false;
  bool alt = false;
  bool shift = false;
  bool super = false;
  // Generated by key repeat while the key is held.
  bool repeat = false;
};

// Which keyboard focus a layer surface asks for. automatic is on_demand when
// the scene has text fields or a key handler, otherwise none. Toplevels and
// lock surfaces always receive keys.
enum class Keyboard : std::uint8_t { automatic, none, on_demand, exclusive };

// How an image fills a width x height box. stretch distorts; contain keeps
// the aspect ratio inside the box (the widget may come out smaller); cover
// keeps the aspect ratio and crops the overflow, centered.
enum class ImageFit : std::uint8_t { stretch, contain, cover };

using ClickHandler = std::function<void(const ClickEvent&)>;
using ScrollHandler = std::function<void(const ScrollEvent&)>;
using TouchHandler = std::function<void(const TouchEvent&)>;
// The pointer entered (true) or left (false) a widget.
using HoverHandler = std::function<void(bool inside)>;
// Return true when the key was handled; other keys go to the focused text field.
using KeyHandler = std::function<bool(const KeyEvent&)>;
using DragHandler = std::function<void(const DragEvent&)>;
using TextHandler = std::function<void(const std::string&)>;
using AuthenticationHandler = std::function<void(bool authenticated)>;
using FocusHandler = std::function<void(const FocusEvent&)>;
using CloseHandler = std::function<void()>;

struct Rectangle {
  float x = 0.0F;
  float y = 0.0F;
  float width = 320.0F;
  float height = 48.0F;
  float radius = 0.0F;
  // TL, TR, BR, BL; negative entries inherit radius.
  std::array<float, 4> corner_radii{-1.0F, -1.0F, -1.0F, -1.0F};
  float border_width = 0.0F;
  std::uint32_t anchor = 0;
  std::uint32_t layer = 2;
  std::array<std::int32_t, 4> margin{0, 0, 0, 0};
  bool position_configured = false;
  bool exclusive = false;
  std::int32_t exclusive_zone = 0;
  bool accepts_input = true;
  std::string surface_namespace = "vw";
  std::array<float, 4> color{0.12F, 0.14F, 0.18F, 1.0F};
  std::array<float, 4> color2{0.12F, 0.14F, 0.18F, 1.0F};
  std::array<float, 4> border_color{1.0F, 1.0F, 1.0F, 1.0F};
  std::array<float, 4> clip{0.0F, 0.0F, 0.0F, 0.0F};
  float clip_radius = 0.0F;
  std::uint32_t gradient = 0;
  bool exact_coverage = false;
  bool visible = true;
  bool raster_visible = true;
  std::string shader;
  std::array<float, 4> shader_params{0.0F, 0.0F, 0.0F, 0.0F};
  std::vector<float> shader_data;

  bool operator==(const Rectangle&) const = default;
};

// Immutable pixel data. Scenes share it rather than copying, so rebuilding
// a scene full of cached text and images costs no pixel copies.
using Pixels = std::shared_ptr<const std::vector<std::uint32_t>>;

// Image pixels held in memory, such as a screen capture: width * height
// values, row by row, each RGBA with red in the low byte.
struct Bitmap {
  std::uint32_t width = 0;
  std::uint32_t height = 0;
  Pixels rgba;

  bool empty() const { return width == 0 || height == 0 || !rgba; }
};

// Per-pixel colour work on an image, applied in the raster shader in this
// order: saturation, hue, colorize, then the multiplying tint.
struct ImageEffect {
  // 1 is unchanged, 0 greys it out, above 1 boosts it.
  float saturation = 1.0F;
  // Degrees around the colour wheel.
  float hue_rotate = 0.0F;
  // Recolours towards this colour by luminance, keeping the image's shading
  // (a multiplying tint only darkens). 0 is off, 1 fully recoloured.
  std::array<float, 4> colorize{1.0F, 1.0F, 1.0F, 1.0F};
  float colorize_amount = 0.0F;

  bool operator==(const ImageEffect&) const = default;
};

struct Raster {
  std::size_t carrier = 0;
  std::uint32_t width = 0;
  std::uint32_t height = 0;
  Pixels rgba;
  bool use_tint = true;
  bool alpha_mask = false;
  bool pixel_snap = false;
  ImageEffect effect;
  // A closed polygon the image is clipped to: x0, y0, x1, y1, ... from 0 to 1
  // across the drawn image. Empty for none.
  std::vector<float> mask;

  std::size_t size() const { return rgba ? rgba->size() : 0; }

  bool operator==(const Raster& other) const {
    return carrier == other.carrier && width == other.width && height == other.height &&
           use_tint == other.use_tint && alpha_mask == other.alpha_mask &&
           pixel_snap == other.pixel_snap && effect == other.effect && mask == other.mask &&
           (rgba == other.rgba || (rgba && other.rgba && *rgba == *other.rgba));
  }
};

struct Interaction {
  std::size_t begin = 0;
  std::size_t end = 0;
  float x = 0.0F;
  float y = 0.0F;
  float width = 0.0F;
  float height = 0.0F;
  bool enabled = true;
  std::array<float, 4> clip{0.0F, 0.0F, 0.0F, 0.0F};
  int text_field = -1;
  ClickHandler on_click;
  DragHandler on_drag_start;
  DragHandler on_drag;
  DragHandler on_drag_end;
  ScrollHandler on_scroll;
  ScrollHandler on_scroll_x;
  TouchHandler on_touch;
  HoverHandler on_hover;
  // Whether the pointer is within the rectangle, for on_hover.
  bool pointer_inside = false;
  std::uint32_t drag_button = 272;
  std::array<float, 4> hover_color{0, 0, 0, 0};
  bool has_hover_color = false;
  float hover_scale = 1.0F;
  float duration = 0.16F;
  bool hovered = false;
  float hover_amount = 0.0F;
  float hover_target = 0.0F;
  std::vector<std::array<float, 4>> original_colors;
  std::vector<std::array<float, 4>> original_bounds;

  bool draggable() const { return on_drag_start || on_drag || on_drag_end; }
};

struct TextFieldState {
  std::string value;
  bool focused = false;
  // Byte offset of the caret, always on a UTF-8 boundary.
  std::size_t caret = 0;
  // Other end of the selection (mouse drag, Shift+motion, Ctrl+A); nothing
  // is selected when unset or equal to the caret.
  std::optional<std::size_t> anchor;
  // Horizontal scroll that keeps the caret visible, in pixels.
  float scroll = 0.0F;
  // Text an input method is still composing (text-input-v3 preedit), kept in
  // value at [preedit_start, preedit_start + preedit_length) until committed.
  std::size_t preedit_start = 0;
  std::size_t preedit_length = 0;

  bool has_selection() const { return anchor && *anchor != caret; }
  std::size_t selection_start() const { return anchor ? std::min(*anchor, caret) : caret; }
  std::size_t selection_end() const { return anchor ? std::max(*anchor, caret) : caret; }
};

// Where a text field's characters are, so clicks can place the caret.
struct TextFieldLayout {
  float padding = 0.0F;
  // Caret x for each character boundary, relative to the unscrolled text
  // origin; offsets index the value (password fields map bullets back).
  std::vector<std::pair<std::size_t, float>> stops;
};

struct TextField {
  std::string id;
  std::shared_ptr<TextFieldState> state;
  std::size_t interaction = 0;
  std::size_t max_length = 4096;
  TextFieldLayout layout;
  TextHandler on_change;
  TextHandler on_submit;
  // Called instead of on_submit for authenticate fields.
  AuthenticationHandler on_authenticated;
  bool password = false;
  bool authenticate = false;
};

struct ScrollState {
  float offset = 0.0F;
  // The listview row last scrolled into view (keep_visible), so the wheel
  // can scroll freely until the selection changes.
  std::optional<std::size_t> kept;
};

struct ScrollArea {
  std::size_t begin = 0;
  std::size_t end = 0;
  float x = 0.0F;
  float y = 0.0F;
  float width = 0.0F;
  float height = 0.0F;
  float maximum = 0.0F;
  float step = 40.0F;
  std::shared_ptr<ScrollState> state;
  bool enabled = true;
};

// Who draws a toplevel's titlebar and borders.
enum class Decorations { automatic, client, server };

struct Scene {
  std::vector<Rectangle> rectangles;
  std::vector<Raster> rasters;
  std::vector<Interaction> interactions;
  std::vector<TextField> text_fields;
  std::vector<ScrollArea> scroll_areas;
  std::uint32_t width = 1;
  std::uint32_t height = 1;
  std::uint32_t anchor = 0;
  std::uint32_t layer = 2;
  std::array<std::int32_t, 4> margin{0, 0, 0, 0};
  bool exclusive = false;
  std::int32_t exclusive_zone = 0;
  bool accepts_input = true;
  std::string surface_namespace = "vw";
  // Layer surfaces: the output's name, or empty for the compositor's choice.
  std::string output;
  bool toplevel = false;
  bool surface_configured = false;
  // The compositor picks this dimension (layer-shell size 0).
  bool fill_width = false;
  bool fill_height = false;
  bool selective_input = false;
  bool focus_grab = false;
  FocusHandler on_focus_activated;
  FocusHandler on_focus_dismissed;
  std::vector<std::array<std::int32_t, 4>> input_regions;
  std::string title = "vw";
  std::string app_id = "vw";
  std::uint32_t toplevel_width = 0;
  std::uint32_t toplevel_height = 0;
  Decorations decorations = Decorations::automatic;
  double refresh_interval = 1.0;
  bool session_lock = false;
  bool lock_surface = false;
  std::string pam_service;
  std::string pam_conf;
  std::string lock_output;

  // False when the build drew nothing: the surface is unmapped until a later
  // build draws something again.
  bool mapped = true;
  // A tween or canvas asked for another frame during this build.
  bool animating = false;
  // The compositor closed the surface (toplevel close, layer surface closed)
  // or a session lock was unlocked. Without a handler the app exits.
  CloseHandler on_closed;
  KeyHandler on_key;
  Keyboard keyboard = Keyboard::automatic;

  void add(Rectangle rectangle);
};

}  // namespace vw
